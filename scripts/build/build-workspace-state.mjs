import { createHash } from "node:crypto";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { readFile, writeFile } from "node:fs/promises";
import { rolldown } from "rolldown";

const root = new URL("../../", import.meta.url);
const destination = new URL("packages/webview/src/state.generated.ts", root);
async function bundle(live) {
	const page = await rolldown({
		cwd: fileURLToPath(root),
		input: fileURLToPath(new URL("packages/webview/src/page.tsx", root)),
		platform: "browser",
		// Consume the same source contracts as the host and type checker, even before package dist is rebuilt.
		tsconfig: "tsconfig.json",
		transform: { jsx: "react-jsx", target: "es2022", define: { "process.env.NODE_ENV": '"production"' } },
		// The offline export swaps the live extension for a null stub, so transport, Markdown and editor code never ship.
		plugins: live
			? []
			: [
					{
						name: "offline-page",
						resolveId(source, importer) {
							if (source === "./app/live/index.ts" && importer) return join(dirname(importer), "app/live/offline.ts");
						},
					},
				],
		logLevel: "warn",
	});
	try {
		const { output } = await page.generate({
			format: "iife",
			name: "WorkspaceView",
			minify: true,
			comments: { legal: false },
		});
		return output[0].code.replace(/<\/script/gi, "<\\/script");
	} finally {
		await page.close();
	}
}
const [liveScript, offlineScript] = await Promise.all([bundle(true), bundle(false)]);
const require = createRequire(new URL("packages/webview/package.json", root));
async function licenses(names) {
	return (
		await Promise.all(
			names.map(async (name) => {
				const directory =
					name === "dompurify"
						? join(dirname(require.resolve(name)), "..")
						: dirname(require.resolve(name + "/package.json"));
				return name + "\n" + (await readFile(join(directory, "LICENSE"), "utf8"));
			}),
		)
	).join("\n");
}
const runtime = ["react", "react-dom", "scheduler", "zustand"];
const license = await licenses([...runtime, "marked", "dompurify", "highlight.js"]);
const offlineLicense = await licenses(runtime);
// Functions, not constants, for the reason `mermaidJs` gives below: every process that loads the host bundle (the
// terminal included) would otherwise hold both page scripts, about 2.5 MB, on its heap from startup.
const source =
	"// Generated by scripts/build/build-workspace-state.mjs. Do not edit.\nexport function workspaceStateJs(): string {\n\treturn " +
	JSON.stringify("/* Bundled dependency licenses\n" + license + "*/\n" + liveScript) +
	";\n}\nexport function offlinePageJs(): string {\n\treturn " +
	JSON.stringify("/* Bundled dependency licenses\n" + offlineLicense + "*/\n" + offlineScript) +
	";\n}\n";
// Mermaid is not part of the page script: the host serves this lazy chunk under the page's own token and the page
// runs it as an inline script only when a document with a diagram opens. The meta policy's 'unsafe-inline' allows it;
// the daemon's hash-only header allows it by its hash, written to a small module so the host need not load the script.
const mermaidDirectory = dirname(require.resolve("mermaid/package.json"));
const mermaidScript =
	"/* Bundled dependency license\nmermaid\n" +
	(await readFile(join(mermaidDirectory, "LICENSE"), "utf8")) +
	"*/\n" +
	(await readFile(join(mermaidDirectory, "dist/mermaid.min.js"), "utf8"));
// A function, not a constant: bundled, a constant's literal sits in the module's lazy init, which V8 compiles eagerly
// (parenthesized function), keeping the whole string on the heap from startup. A function body stays uncompiled until
// the first call.
const mermaidSource =
	"// Generated by scripts/build/build-workspace-state.mjs. Do not edit.\nexport function mermaidJs(): string {\n\treturn " +
	JSON.stringify(mermaidScript) +
	";\n}\n";
const mermaidHashSource =
	"// Generated by scripts/build/build-workspace-state.mjs. Do not edit.\n" +
	"/** The CSP hash source of `mermaidJs()`, the text the page runs as an inline script. */\n" +
	`export const MERMAID_SCRIPT_HASH: string = "sha256-${createHash("sha256").update(mermaidScript, "utf8").digest("base64")}";\n`;
const mermaidDestination = new URL("packages/webview/src/mermaid.generated.ts", root);
const mermaidHashDestination = new URL("packages/webview/src/mermaid-hash.generated.ts", root);
const outputs = [
	[destination, source],
	[mermaidDestination, mermaidSource],
	[mermaidHashDestination, mermaidHashSource],
];
if (process.argv.includes("--check")) {
	const current = await Promise.all(outputs.map(([file]) => readFile(file, "utf8").catch(() => undefined)));
	if (outputs.some(([, text], index) => current[index] !== text))
		throw new Error("Workspace state bundle is stale. Run yarn run generate:workspace.");
} else await Promise.all(outputs.map(([file, text]) => writeFile(file, text)));
