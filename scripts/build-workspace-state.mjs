import { build } from "esbuild";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const destination = new URL("packages/webview/src/state.generated.ts", root);
async function bundle(live) {
	const result = await build({
		absWorkingDir: fileURLToPath(root),
		entryPoints: ["packages/webview/src/page.tsx"],
		bundle: true,
		write: false,
		platform: "browser",
		format: "iife",
		globalName: "WorkspaceView",
		jsx: "automatic",
		// The offline export swaps the live extension for a null stub, so transport, Markdown and editor code never ship.
		plugins: live
			? []
			: [
					{
						name: "offline-page",
						setup(builder) {
							builder.onResolve({ filter: /^\.\/app\/live\/index\.ts$/ }, ({ resolveDir }) => ({
								path: join(resolveDir, "app/live/offline.ts"),
							}));
						},
					},
				],
		minify: true,
		legalComments: "none",
		target: "es2022",
		define: { "process.env.NODE_ENV": '"production"' },
	});
	return result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
}
const [liveScript, offlineScript] = await Promise.all([bundle(true), bundle(false)]);
const require = createRequire(new URL("packages/webview/package.json", root));
async function licenses(names) {
	return (
		await Promise.all(
			names.map(async (name) => {
				const directory =
					name === "dompurify"
						? join(dirname(require.resolve(name)), "..")
						: dirname(require.resolve(name + "/package.json"));
				return name + "\n" + (await readFile(join(directory, "LICENSE"), "utf8"));
			}),
		)
	).join("\n");
}
const runtime = ["react", "react-dom", "scheduler", "zustand"];
const license = await licenses([...runtime, "marked", "dompurify", "highlight.js"]);
const offlineLicense = await licenses(runtime);
const source =
	"// Generated by scripts/build-workspace-state.mjs. Do not edit.\nexport const WORKSPACE_STATE_JS = " +
	JSON.stringify("/* Bundled dependency licenses\n" + license + "*/\n" + liveScript) +
	";\nexport const OFFLINE_PAGE_JS = " +
	JSON.stringify("/* Bundled dependency licenses\n" + offlineLicense + "*/\n" + offlineScript) +
	";\n";
if (process.argv.includes("--check")) {
	if ((await readFile(destination, "utf8")) !== source)
		throw new Error("Workspace state bundle is stale. Run npm run generate:workspace.");
} else await writeFile(destination, source);
