function flagsById(
	...sources: readonly (readonly [readonly string[], keyof ModelCacheFlags])[]
): Record<string, ModelCacheFlags> {
	const table: Record<string, ModelCacheFlags> = {};
	for (const [ids, flag] of sources) {
		for (const id of ids) table[id] = { ...table[id], [flag]: true };
	}
	return Object.fromEntries(Object.entries(table).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

/** The documented flags above, one entry per model id and host. */
export function buildCacheFlagTable(): CacheFlagTable {
	return {
		openai: flagsById([OPENAI_EXPLICIT_MODE_IDS, "explicitMode"], [OPENAI_LONG_RETENTION_IDS, "longRetention"]),
		azure: flagsById(
			[AZURE_INSTRUCTION_BREAKPOINT_IDS, "instructionBreakpoints"],
			[AZURE_LONG_RETENTION_IDS, "longRetention"],
		),
		openrouter: flagsById([OPENROUTER_EXPLICIT_MARKER_IDS, "explicitMarkers"]),
	};
}

/** Source of `src/utils/cache-capability-flags.generated.ts`. */
export function serializeCacheFlagTable(table: CacheFlagTable): string {
	return `// This file is auto-generated by scripts/generate-models.ts
// Do not edit manually - run 'yarn run generate-models' to update

import type { CacheFlagTable } from "./cache-capability-data.ts";

/** Per-model prompt-cache facts from scripts/generate-models/cache-flags.ts. */
export const CACHE_CAPABILITY_FLAGS: CacheFlagTable = ${JSON.stringify(table, null, "\t")};
`;
}
