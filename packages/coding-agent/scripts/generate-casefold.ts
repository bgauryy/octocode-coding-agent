#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageDirectory = fileURLToPath(new URL("..", import.meta.url));
const sourcePath = resolve(packageDirectory, "test/octocode/fixtures/unicode16.json");
const targetPath = resolve(packageDirectory, "src/octocode/team/casefold-table.generated.ts");

export interface CasefoldSource {
	version: string;
	casefold: Record<string, number[]>;
}

/** The text of `casefold-table.generated.ts` for a parsed `unicode16.json`. */
export function renderCasefoldTable(table: CasefoldSource): string {
	const hex = (value: number) => value.toString(16).toUpperCase();
	const lines = Object.entries(table.casefold)
		.map(([from, to]): [number, number[]] => [Number(from), to])
		.sort((a, b) => a[0] - b[0])
		.map(([from, to]) => `${hex(from)}:${to.map(hex).join(" ")}`);
	return [
		"// Generated by scripts/generate-casefold.ts from test/octocode/fixtures/unicode16.json. Do not edit; run yarn run generate:casefold.",
		`export const CASE_FOLDING_UNICODE_VERSION = "${table.version}";`,
		"",
		"/** One `<code point>:<folded code points, space separated>` per line, in hexadecimal: Unicode full case folding (CaseFolding.txt statuses C and F). */",
		`export const CASE_FOLDING = \`\n${lines.join("\n")}\n\`;`,
		"",
	].join("\n");
}

function generateCasefold(): void {
	const table = JSON.parse(readFileSync(sourcePath, "utf8")) as CasefoldSource;
	writeFileSync(targetPath, renderCasefoldTable(table), "utf-8");
	console.log("Generated packages/coding-agent/src/octocode/team/casefold-table.generated.ts");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	generateCasefold();
}
